// Helper to resolve language string ('Telugu (తెలుగు)' -> 'te')
export const getLangCode = (rawLang) => {
  if (!rawLang) return 'te';
  if (rawLang.includes('Telugu') || rawLang.includes('తెలుగు')) return 'te';
  if (rawLang.includes('Hindi') || rawLang.includes('हिंदी')) return 'hi';
  if (rawLang.includes('Marathi') || rawLang.includes('मराठी')) return 'mr';
  if (rawLang.includes('Tamil') || rawLang.includes('தமிழ்')) return 'ta';
  if (rawLang.includes('Kannada') || rawLang.includes('ಕನ್ನಡ')) return 'kn';
  return 'en';
};

const initialLang = localStorage.getItem('localfarm_lang');
const initialCode = getLangCode(initialLang);

